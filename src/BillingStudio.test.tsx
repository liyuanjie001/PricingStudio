import { cleanup, fireEvent, render, screen, within } from '@testing-library/react';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import App from './App';
import { STORAGE_KEY } from './storage';
import { restoreState } from './domain';

vi.mock('./export', () => ({ exportPlan: vi.fn().mockResolvedValue(undefined) }));
beforeEach(() => localStorage.clear());
afterEach(cleanup);
const comparison = () => screen.getByRole('region', { name: '全部套餐对比' });
const change = (label: string, value: string) => fireEvent.change(screen.getByLabelText(label), { target: { value } });

describe('unified comparison and billing UI', () => {
  it('uses the same row styling for personal and team packages across billing cycles', () => {
    render(<App />);
    const personal = screen.getByRole('row', { name: '基础套餐对比' });
    const team = screen.getByRole('row', { name: '团队套餐 1对比' });
    expect(personal).not.toHaveClass('annual-row');
    expect(team).not.toHaveClass('annual-row');
    fireEvent.click(screen.getByRole('checkbox', { name: /按年购买/ }));
    expect(personal).not.toHaveClass('annual-row');
    expect(personal).toHaveClass('selected-row');
    expect(within(personal).getByText('年付')).toBeInTheDocument();
    expect(team).not.toHaveClass('annual-row');
    fireEvent.click(within(team).getByRole('button', { name: '团队套餐 1' }));
    fireEvent.click(screen.getByRole('checkbox', { name: /按年购买/ }));
    expect(team).not.toHaveClass('annual-row');
    expect(team).toHaveClass('selected-row');
    expect(within(team).getByText('年付')).toBeInTheDocument();
    expect(personal).not.toHaveClass('annual-row');
    expect(personal).not.toHaveClass('selected-row');
    fireEvent.click(screen.getByRole('checkbox', { name: /按年购买/ }));
    expect(team).not.toHaveClass('annual-row');
    expect(personal).not.toHaveClass('annual-row');
  });
  it('selects personal and team calculators by clicking row cells and highlights the active row', () => {
    render(<App />);
    const team = screen.getByRole('row', { name: '团队套餐 1对比' });
    fireEvent.click(within(team).getByText('团队版'));
    expect(screen.getByLabelText('每席原价')).toBeInTheDocument();
    expect(team).toHaveAttribute('aria-current', 'true');
    const personal = screen.getByRole('row', { name: '标准套餐对比' });
    fireEvent.click(within(personal).getByText('季付'));
    expect(screen.getByLabelText('套餐名称')).toHaveValue('标准套餐');
    expect(personal).toHaveClass('selected-row');
    expect(team).not.toHaveAttribute('aria-current');
  });
  it('does not switch calculators while editing inputs or using nested row controls', () => {
    render(<App />);
    fireEvent.click(screen.getByRole('row', { name: '团队套餐 1对比' }));
    const input = screen.getByLabelText('基础套餐原价');
    input.focus(); fireEvent.click(input);
    change('基础套餐原价', '123');
    fireEvent.keyDown(input, { key: 'Enter' });
    expect(input).toHaveFocus();
    expect(screen.getByLabelText('每席原价')).toBeInTheDocument();
    fireEvent.click(screen.getByRole('button', { name: '删除基础套餐' }));
    expect(screen.getByLabelText('每席原价')).toBeInTheDocument();
    fireEvent.click(screen.getByRole('button', { name: '取消删除' }));
    expect(screen.getByLabelText('每席原价')).toBeInTheDocument();
  });
  it('supports Enter and Space to select focused rows', () => {
    render(<App />);
    const team = screen.getByRole('row', { name: '团队套餐 1对比' });
    team.focus(); fireEvent.keyDown(team, { key: 'Enter' });
    expect(screen.getByLabelText('每席原价')).toBeInTheDocument();
    const personal = screen.getByRole('row', { name: '标准套餐对比' });
    personal.focus(); fireEvent.keyDown(personal, { key: ' ' });
    expect(screen.getByLabelText('套餐名称')).toHaveValue('标准套餐');
  });
  it('keeps both editions visible, and opens the selected calculator from its row', () => {
    render(<App />);
    expect(within(comparison()).getAllByRole('row')).toHaveLength(6);
    fireEvent.click(within(comparison()).getByRole('button', { name: '团队套餐 1' }));
    expect(screen.getByLabelText('每席原价')).toBeInTheDocument();
    expect(within(comparison()).getAllByRole('row')).toHaveLength(6);
    change('基础套餐原价', '123');
    expect(screen.getByLabelText('每席原价')).toBeInTheDocument();
    fireEvent.click(within(comparison()).getByRole('button', { name: '基础套餐' }));
    expect(screen.getByLabelText('套餐原价')).toHaveValue('123');
    expect(within(comparison()).getByRole('button', { name: '团队套餐 1' })).toBeInTheDocument();
  });
  it('creates an independently editable annual personal package and preserves its quarterly source', () => {
    render(<App />);
    change('套餐原价', '100'); change('优惠百分比输入', '10'); change('毛利率', '40'); change('账号数量', '1');
    fireEvent.click(screen.getByRole('button', { name: '另建年付套餐' }));
    expect(screen.getByRole('checkbox', { name: /按年购买/ })).toBeChecked();
    expect(screen.getByLabelText('套餐原价')).toHaveValue('400');
    expect(screen.getByLabelText('发放积分')).toHaveValue('560');
    expect(screen.getByTestId('account-cost')).toHaveTextContent('104.00');
    expect(screen.getByTestId('actual-profit')).toHaveTextContent('144.00');
    change('套餐原价', '500'); change('优惠百分比输入', '20');
    expect(screen.getByTestId('configured-credits')).toHaveTextContent('830');
    expect(screen.getByLabelText('发放积分')).toHaveValue('830');
    expect(within(comparison()).getAllByRole('row')).toHaveLength(7);
    fireEvent.click(within(comparison()).getByRole('button', { name: '基础套餐' }));
    expect(screen.getByRole('checkbox', { name: /按年购买/ })).not.toBeChecked();
    expect(screen.getByLabelText('套餐原价')).toHaveValue('100');
    expect(screen.getByLabelText('优惠百分比输入')).toHaveValue('10');
    fireEvent.click(screen.getByRole('button', { name: '团队版' }));
    expect(screen.getByRole('checkbox', { name: /按年购买/ })).not.toBeChecked();
    expect(screen.getByTestId('team-sale-price')).toHaveTextContent('400.00');
  });
  it('stores annual team configuration independently and preserves fixed credits when adding seats', () => {
    render(<App />); fireEvent.click(screen.getByRole('button', { name: '团队版' }));
    fireEvent.click(screen.getByRole('button', { name: '另建年付套餐' }));
    expect(screen.getByLabelText('每席原价')).toHaveValue('800');
    expect(screen.getByTestId('seat-credits')).toHaveTextContent('1,480');
    fireEvent.click(screen.getByRole('button', { name: '增加一个席位' }));
    expect(screen.getByTestId('seat-credits')).toHaveTextContent('1,480');
    expect(screen.getByTestId('team-credits')).toHaveTextContent('4,440');
    expect(screen.getByTestId('team-sale-price')).toHaveTextContent('2,400.00');
    expect(screen.getByLabelText('团队毛利率')).toHaveValue('54.33');
    change('每席原价', '1000');
    expect(screen.getByTestId('seat-credits')).toHaveTextContent('2,153');
    fireEvent.click(within(comparison()).getByRole('button', { name: '团队套餐 1' }));
    expect(screen.getByRole('checkbox', { name: /按年购买/ })).not.toBeChecked();
    expect(screen.getByLabelText('每席原价')).toHaveValue('200');
    expect(screen.getByLabelText('套餐席位数')).toHaveValue('2');
  });
  it('remembers individual billing cycles and editable totals after reload', () => {
    const view = render(<App />);
    fireEvent.click(screen.getByRole('checkbox', { name: /按年购买/ }));
    change('套餐原价', '600');
    fireEvent(window, new Event('pagehide'));
    const plan = restoreState(localStorage.getItem(STORAGE_KEY)!).plans[0];
    expect(plan.packages[0]).toMatchObject({ billingCycle: 'annual', listPrice: '600' });
    expect(plan.packages[1].billingCycle).toBe('quarterly');
    view.unmount(); render(<App />);
    expect(screen.getByRole('checkbox', { name: /按年购买/ })).toBeChecked();
    expect(screen.getByLabelText('套餐原价')).toHaveValue('600');
    expect(screen.getByLabelText('基础套餐原价')).toHaveValue('600');
    fireEvent.click(screen.getByRole('button', { name: '团队版' }));
    expect(screen.getByRole('checkbox', { name: /按年购买/ })).not.toBeChecked();
  });
});
